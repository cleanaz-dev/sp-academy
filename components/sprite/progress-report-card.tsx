import { FileBarChart, CheckCircle2, TrendingUp, AlertCircle } from "lucide-react";

export interface ProgressReportData {
  summary?: string;
  overallScore?: number;
  strengths?: string[];
  focusAreas?: string[];
}

export function ProgressReportCard({ data }: { data: ProgressReportData }) {
  return (
    <div className="rounded-3xl border border-primary/40 bg-gradient-to-br from-primary/15 via-slate-900/90 to-slate-950 p-5 shadow-xl space-y-4">
      <div className="flex items-center justify-between border-b border-white/10 pb-3">
        <div className="flex items-center gap-2.5">
          <div className="flex h-9 w-9 items-center justify-center rounded-xl bg-primary/20 border border-primary/40 text-primary">
            <FileBarChart className="h-4 w-4" />
          </div>
          <div>
            <h4 className="text-xs font-black uppercase tracking-wider text-white">
              Progress Report
            </h4>
            <span className="text-[10px] font-semibold text-accent">
              Generated by Spoon Intelligence
            </span>
          </div>
        </div>

        {data.overallScore != null && (
          <div className="rounded-2xl bg-accent/20 border border-accent/40 px-3 py-1 text-right">
            <span className="block text-[9px] font-black uppercase text-accent">Mastery</span>
            <span className="text-sm font-black text-white">{data.overallScore}%</span>
          </div>
        )}
      </div>

      {data.summary && (
        <p className="text-sm font-medium text-slate-200 leading-relaxed">
          {data.summary}
        </p>
      )}

      <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-1">
        {data.strengths && data.strengths.length > 0 && (
          <div className="rounded-2xl border border-accent/20 bg-accent/5 p-3 space-y-1.5">
            <span className="flex items-center gap-1.5 text-[10px] font-black uppercase tracking-wider text-accent">
              <TrendingUp className="h-3.5 w-3.5" /> Strengths
            </span>
            {data.strengths.map((item, i) => (
              <div key={i} className="flex items-center gap-1.5 text-xs text-white font-medium">
                <CheckCircle2 className="h-3 w-3 text-accent shrink-0" />
                <span>{item}</span>
              </div>
            ))}
          </div>
        )}

        {data.focusAreas && data.focusAreas.length > 0 && (
          <div className="rounded-2xl border border-tertiary/30 bg-tertiary/10 p-3 space-y-1.5">
            <span className="flex items-center gap-1.5 text-[10px] font-black uppercase tracking-wider text-tertiary">
              <AlertCircle className="h-3.5 w-3.5" /> Next Focus
            </span>
            {data.focusAreas.map((item, i) => (
              <div key={i} className="text-xs text-white font-medium pl-1 border-l-2 border-tertiary/50">
                {item}
              </div>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}